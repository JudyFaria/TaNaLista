"""Portas (interfaces) que a camada de aplicação precisa.

Os casos de uso dependem destas abstrações, nunca de implementações
concretas. Trocar o JSON pelo Firestore, por exemplo, significa apenas criar
novas classes que satisfaçam estes protocolos (inversão de dependência).
"""

from __future__ import annotations

from collections.abc import Iterable
from typing import Protocol

from app.application.dto import Notification
from app.domain.entities import Group, ShoppingItem, User


class UserRepository(Protocol):
    def add(self, user: User) -> None: ...
    def get(self, user_id: str) -> User | None: ...
    def get_by_username(self, username: str) -> User | None: ...
    def get_many(self, user_ids: Iterable[str]) -> dict[str, User]: ...


class GroupRepository(Protocol):
    def save(self, group: Group) -> None: ...
    def get(self, group_id: str) -> Group | None: ...
    def get_by_invite_code(self, code: str) -> Group | None: ...
    def list_for_user(self, user_id: str) -> list[Group]: ...
    def search_public(self, query: str, limit: int) -> list[Group]: ...
    def delete(self, group_id: str) -> None: ...


class ItemRepository(Protocol):
    def save(self, item: ShoppingItem) -> None: ...
    def get(self, item_id: str) -> ShoppingItem | None: ...
    def list_by_group(self, group_id: str) -> list[ShoppingItem]: ...
    def delete(self, item_id: str) -> None: ...
    def delete_by_group(self, group_id: str) -> None: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


class TokenService(Protocol):
    def issue(self, user_id: str) -> str: ...

    def verify(self, token: str) -> str:
        """Retorna o ``user_id`` ou lança ``AuthenticationError``."""
        ...


class EventPublisher(Protocol):
    def publish(self, user_ids: Iterable[str], notification: Notification) -> None: ...
